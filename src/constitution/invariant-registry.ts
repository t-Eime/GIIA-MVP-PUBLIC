const BY_ID = new Map(
  CONSTITUTIONAL_INVARIANTS.map((entry) => [entry.id, entry]),
);

export function getConstitutionalInvariant(
  id: string,
): ConstitutionalInvariant | undefined {
  return BY_ID.get(id);
}

export function listConstitutionalInvariants(): readonly ConstitutionalInvariant[] {
  return CONSTITUTIONAL_INVARIANTS;
}

export function isProtectedConstitutionalInvariant(id: string): boolean {
  return getConstitutionalInvariant(id)?.protected === true;
}

export function isConstitutionalInvariantActive(id: string): boolean {
  return getConstitutionalInvariant(id)?.status === "ACTIVE";
}

export function assertInvariantExists(id: string): ConstitutionalInvariant {
  const result = getConstitutionalInvariant(id);

  if (!result) {
    throw new Error(`UNKNOWN_CONSTITUTIONAL_INVARIANT:${id}`);
  }

  return result;
}

export function assertProtectedInvariant(id: string): ConstitutionalInvariant {
  const result = assertInvariantExists(id);

  if (!result.protected) {
    throw new Error(`INVARIANT_NOT_PROTECTED:${id}`);
  }

  return result;
}
